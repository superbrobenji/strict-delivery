class TestForbiddenContent(TplCase):
    def rendered(self):
        return [claude_block_body(cfg()), gitignore_block_body(cfg()), ci_workflow(cfg(), "v0.1.0", "o/n"),
                ci_workflow(cfg(), SHA40, "o/n")]

    def raw_templates(self):
        found = []
        for dirpath, dirs, files in os.walk(TEMPLATES_DIR):
            for f in files:
                found.append(os.path.relpath(os.path.join(dirpath, f), TEMPLATES_DIR).replace(os.sep, "/"))
        return sorted(found)

    def test_templates_hold_no_forbidden_strings(self):  # FC1-FC6, spec 2 row C-1
        names = self.raw_templates()
        self.assertEqual(names, sorted(RAW_NAMES))
        for name in names:
            with self.subTest(raw=name):
                self.assertEqual(forbidden_hits(raw(name)), [])
        for i, text in enumerate(self.rendered()):
            with self.subTest(rendered=i):
                self.assertEqual(forbidden_hits(text), [])

    def test_seeded_template_hit_fails(self):  # FC7, FC8
        self.assertEqual(set(SAMPLE), {n for n, _ in FORBIDDEN})
        texts = [(n, raw(n)) for n in RAW_NAMES] + [("rendered%d" % i, t) for i, t in enumerate(self.rendered())]
        for label, text in texts:
            for name in SAMPLE:
                with self.subTest(file=label, name=name):
                    self.assertEqual([h[0] for h in forbidden_hits(text + "\n" + SAMPLE[name])], [name])

    def test_seeded_hit_after_last_line(self):  # FC9
        for label, text in [(n, raw(n)) for n in RAW_NAMES]:
            with self.subTest(file=label):
                last = text.rstrip("\n").split("\n")[-1]
                hits = forbidden_hits(text.rstrip("\n") + " lap\ntimer\n")
                self.assertEqual([h[0] for h in hits], ["lap-timer"])
                self.assertEqual(forbidden_hits(text + "lap\ntimer\n")[0][0], "lap-timer")
                self.assertTrue(last)

    def test_templates_are_ascii_lf(self):  # FC10
        for name in RAW_NAMES:
            text = raw(name)
            self.assertTrue(all(c == "\n" or " " <= c <= "~" for c in text), name)

    def test_templates_end_in_one_newline(self):  # FC12, FC13
        for name in RAW_NAMES:
            text = raw(name)
            self.assertTrue(text.endswith("\n") and not text.endswith("\n\n"), name)
            self.assertNotIn("\r", text)
            self.assertNotIn("\t", text)
            self.assertNotIn("﻿", text)

    def test_template_placeholders_are_the_documented_keys(self):  # FC14
        def keys(name):
            return sorted(set(re.findall(r"(?<!\$)\{\{([a-z][a-z0-9_]*)\}\}", raw(name))))
