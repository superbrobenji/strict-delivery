def split_steps(lines):
    """The steps of a job's ``steps:`` list: a step starts at a ``      - `` line, together with the ``      #``
    comment lines directly before it; the lines after belong to it up to the next step."""
    steps, pending = [], []
    for line in lines:
        if line.startswith("      #"):
            pending.append(line)
        elif line.startswith("      - "):
            steps.append(pending + [line])
            pending = []
        else:
            steps[-1].append(line)
    return steps


def on_block(text):
    lines = text.split("\n")
    i = lines.index("on:")
    j = i + 1
    while lines[j] != "":
        j += 1
    return lines[i:j]


def actions_match(ci_text, repo_text, label="ubuntu-24.04"):
    return uses(ci_text) == uses(repo_text) and len(uses(ci_text)) >= 1 and label in runner_labels(repo_text)


def evaluate(expr, event, base_ref, default):
    """The one ``cond && a || b`` form of the workflow's ``--base`` expression."""
    left, _, other = expr.partition(" || ")
    cond, _, first = left.partition(" && ")
    values = {"github.base_ref": base_ref, "github.event.repository.default_branch": default}
    holds = cond == "github.event_name == 'pull_request'" and event == "pull_request"
    return values[first] if holds and values[first] else values[other]


def base_expr(text):
    m = re.search(r"--base origin/\$\{\{ (.*) \}\}", text)
    return m.group(1)


class TplCase(unittest.TestCase):
    def tpl(self, files):
        td = tempfile.TemporaryDirectory()
        self.addCleanup(td.cleanup)
        d = os.path.realpath(td.name)
        for name, data in files.items():
            path = os.path.join(d, *name.split("/"))
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "wb") as fh:
                fh.write(data if isinstance(data, bytes) else data.encode("utf-8"))
        p = mock.patch.object(templates, "TEMPLATES_DIR", d)
        p.start()
        self.addCleanup(p.stop)
        return d

    def copy_real(self, **changes):
        files = {n: raw(n) for n in RAW_NAMES}
        files.update(changes)
        return self.tpl(files)


