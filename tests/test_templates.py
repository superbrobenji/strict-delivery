def uses(text):
    """The ``uses:`` values of a workflow text: the first word after ``uses:``, a trailing comment dropped."""
    return {m.group(1) for m in re.finditer(r"(?m)^\s*(?:-\s+)?uses:\s*(\S+)", text)}


def runner_labels(text):
    m = re.search(r"(?m)^\s*os:\s*\[([^\]]*)\]", text)
    return [x.strip() for x in m.group(1).split(",")] if m else []


def job_lines(text, name):
    """The lines of one job (from its ``  <name>:`` line to the next job or the end)."""
    lines = text.split("\n")
    start = lines.index("  %s:" % name)
    out = []
    for line in lines[start:]:
        if out and re.match(r"  \S", line) and not line.startswith("  #"):
            break
        out.append(line)
    while out and (out[-1] == "" or out[-1].startswith("  #")):
        out.pop()
    return out


