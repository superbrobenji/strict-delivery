    def _numeric(self, digits):
        n = "1" * digits
        for limit in INT_LIMITS:
            with int_limit(limit):
                self.assertEqual(ci_pin(n + ".0.0", None), "v" + n + ".0.0")
                self.assertEqual(ci_workflow(cfg(), "v%s.0.0" % n, "o/n").count("v%s.0.0" % n), 1)
                self.assertEqual(ci_workflow(cfg(), SHA40, "o/" + n).count("github.com/o/" + n), 1)
                self.assertEqual(ci_workflow(cfg(base=n + ".x"), SHA40, "o/n").count("[%s.x]" % n), 1)

    def test_templates_no_unicode_database_read(self):  # VR5
        c = chr(0xA7C0)
        with mock.patch.object(unicodedata, "category", side_effect=AssertionError("UCD lookup")):
            self.assertEqual(ci_pin("1.2.3", None), "v1.2.3")
            for bad in (lambda: ci_pin("0.0.0", c * 40), lambda: ci_pin("%s.0.0" % c, None),
                        lambda: ci_workflow(cfg(), c * 40, "o/n"), lambda: ci_workflow(cfg(), SHA40, "o/" + c),
                        lambda: ci_workflow(cfg(base=c), SHA40, "o/n")):
                with self.assertRaises(GateError):
                    bad()
            self.assertEqual(pin_of("git fetch --depth 1 https://github.com/o/n %s\n" % (c * 40)), None)
            self.assertTrue(claude_block_body(cfg()).endswith("\n"))
            self.assertTrue(gitignore_block_body(cfg()).endswith("\n"))

    def test_templates_no_case_folding(self):  # VR7, CP8, RN25
        for v in ("A" * 40, "a" * 39 + "A"):
            with self.assertRaises(GateError):
                ci_pin("0.0.0", v)
        with self.assertRaises(GateError):
            ci_workflow(cfg(), "V0.1.0", "o/n")
        src = read(templates.__file__)
        self.assertNotRegex(src, r"\.lower\(|\.upper\(|\.casefold\(|\.title\(")

    def test_templates_source_has_no_exception_group(self):  # VR8, VR9
        src = read(templates.__file__)
        tree = ast.parse(src)
        for node in ast.walk(tree):
            self.assertNotIsInstance(node, getattr(ast, "TryStar", ()) or ())
            if isinstance(node, ast.Name):
                self.assertNotIn(node.id, ("BaseExceptionGroup", "ExceptionGroup"))
            if isinstance(node, ast.Attribute):
                self.assertNotIn(node.attr, ("isprintable", "isalnum", "isdecimal", "isalpha", "isdigit", "isnumeric"))
            if isinstance(node, ast.keyword):
                self.assertNotIn(node.arg, ("type", "choices"))
        self.assertNotIn("unicodedata", src)
        self.assertNotIn("int(", src)

