class PreCommitTest(HookCase):
    def test_unstaged_change_refuses_commit_before_gates(self):  # C2-C5, C10; F-3
        def staged_then_changed(d):
            self.stage_then_change(d)
            return ["a.txt"]

        def changed_other_staged(d):
            write_file(d, "b.txt", "two\n")
            git(d, "add", "b.txt")
            write_file(d, "a.txt", "two\n")
            return ["a.txt"]

        def deleted(d):
            write_file(d, "b.txt", "two\n")
            git(d, "add", "b.txt")
            os.unlink(os.path.join(d, "a.txt"))
            return ["a.txt"]

        def intent_to_add(d):
            write_file(d, "b.txt", "two\n")
            git(d, "add", "b.txt")
            write_file(d, "n.txt")
            git(d, "add", "-N", "n.txt")
            return ["n.txt"]

        def several(d):
            write_file(d, "c.txt")
            git(d, "add", "c.txt")
            write_file(d, "b.txt", "two\n")
            write_file(d, "a.txt", "two\n")
            return ["a.txt", "b.txt"]

        for label, setup in (("C2", staged_then_changed), ("C3", changed_other_staged), ("C4", deleted),
                             ("C5", intent_to_add), ("C10", several)):
            with self.subTest(label):
                d = self.repo(install=True)
                want = setup(d)
                before = self.head(d)
                rc, out = self.commit(d)
                self.assertNotEqual(rc, 0)
                for path in want:
                    self.assertIn(unstaged_line(path), out)
                self.assertEqual("".join(unstaged_line(p) for p in want), out)  # no gate line, in order
                self.assertEqual(self.head(d), before)
        d = self.repo()  # the same refusal in process: no gate ran
        called = self.fake_gates()
        self.stage_then_change(d)
        rc, out, err = self.hook(["pre-commit", "--root", d])
        self.assertEqual((rc, out, err), (1, unstaged_line("a.txt"), ""))
        self.assertEqual(called, [])

