def shim_text(name, framework=FRAMEWORK):
    return ("#!/bin/sh\n%s\ncd '%s' && exec python3 -m gates githook %s --root \"$OLDPWD\" \"$@\"\n"
            % (HEADER, framework, name))


def write_file(root, rel, data="one\n"):
    p = os.path.join(root, rel)
    os.makedirs(os.path.dirname(p) or root, exist_ok=True)
    with open(p, "wb") as fh:
        fh.write(data if isinstance(data, bytes) else data.encode("utf-8"))
    return p


def put(path, data):
    return write_file(os.path.dirname(path), os.path.basename(path), data)


def read_bytes(path):
    with open(path, "rb") as fh:
        return fh.read()


class HookCase(GitIsolatedTestCase):
    """Fixture repositories, the PATH of the preamble, real git runs and in-process hook runs."""

    def setUp(self):
        super().setUp()
        self.bin = os.path.join(self.tmp, "bin")
        os.mkdir(self.bin)
        os.symlink(sys.executable, os.path.join(self.bin, "python3"))  # the shim's python3 is this interpreter
        self._repos = itertools.count()

    # ---- fixtures
    def repo(self, profile="standard", commands=None, files=("a.txt", "b.txt"), install=False, config=None):
        d = os.path.join(self.tmp, "repo%d" % next(self._repos))
        os.mkdir(d)
        cfg = dict(minimal_config(), profile=profile)
        if commands is not None:
            cfg["commands"] = commands
        make_repo(d, config if config is not None else cfg)
        for name in files:
            write_file(d, name)
        commit_all(d, "files")
        if install:
            self.assertEqual(githooks.install(d, FRAMEWORK), [])
        return d

    def env(self, **extra):
        e = dict(os.environ)
        e["LC_ALL"] = "C"
        e["PATH"] = self.bin + os.pathsep + e["PATH"]
        e.update(extra)
        return e

    def run_proc(self, argv, cwd=None, env=None, stdin=None):
        p = subprocess.run(argv, cwd=cwd, env=env or self.env(), input=stdin, stdout=subprocess.PIPE,
                           stderr=subprocess.STDOUT)
        return p.returncode, p.stdout.decode("utf-8", "replace")

    def git_run(self, root, *args):
        return self.run_proc(["git", "-C", root] + list(args))

    def commit(self, root, *args):
        return self.git_run(root, "commit", "-q", "-m", "change", *args)

    def head(self, root):
        return git(root, "rev-parse", "HEAD")

    def stage_then_change(self, root, name="a.txt"):
        write_file(root, name, "two\n")
        git(root, "add", name)
        write_file(root, name, "three\n")

    # ---- fake gates: record what run_all runs
    def fake_gates(self):
        called = []
        names, mods = {}, {}
        for gate in GATES5:
            mod = types.ModuleType("tests_fake_githook_" + gate)

            def check(args, gate=gate):
                called.append(gate)
                res = Result(gate)
                res.passed(gate + ".ok")
                return res
            mod.check = check
            names[gate] = mod.__name__
            mods[mod.__name__] = mod
        for patcher in (mock.patch.dict(gates_main.GATES, names), mock.patch.dict(sys.modules, mods)):
            patcher.start()
            self.addCleanup(patcher.stop)
        return called

    # ---- in-process runs
    def hook(self, argv, stdin=b"", env=None):
        out, err = io.StringIO(), io.StringIO()
        text = io.TextIOWrapper(io.BytesIO(stdin), encoding="utf-8", newline="")
        with mock.patch.dict(os.environ, env or {}), mock.patch.object(sys, "stdout", out), \
                mock.patch.object(sys, "stderr", err), mock.patch.object(sys, "stdin", text):
            rc = githooks.main(argv)
        return rc, out.getvalue(), err.getvalue()

    def manage(self, argv, env=None):
        out, err = io.StringIO(), io.StringIO()
        with mock.patch.dict(os.environ, env or {}), mock.patch.object(sys, "stdout", out), \
                mock.patch.object(sys, "stderr", err):
            rc = githooks.manage(argv)
        return rc, out.getvalue(), err.getvalue()

    def hook_path(self, root, name):
        return os.path.join(gitinfo.hooks_dir(root), name)

    def push_line(self, local_ref, local_sha, remote_ref="refs/heads/main", remote_sha=ZEROS):
        return ("%s %s %s %s\n" % (local_ref, local_sha, remote_ref, remote_sha)).encode("utf-8")


