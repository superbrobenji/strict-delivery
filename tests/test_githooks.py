def spy_runs():
    """Patch subprocess.run in gitinfo to record (argv, env) of each call and still run it."""
    calls = []
    real = subprocess.run

    def spy(argv, *a, **kw):
        calls.append((list(argv), dict(kw.get("env") or {})))
        return real(argv, *a, **kw)
    return calls, mock.patch.object(gitinfo.subprocess, "run", spy)


