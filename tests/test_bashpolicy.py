def append_config(root, text):
    with open(os.path.join(root, ".git", "config"), "ab") as fh:
        fh.write(text if isinstance(text, bytes) else text.encode("utf-8"))


class Repo(GitIsolatedTestCase):
    def repo(self, name="r", profile=None, commands=None):
        d = os.path.join(self.tmp, name)
        os.mkdir(d)
        cfg = minimal_config()
        if profile:
            cfg["profile"] = profile
        if commands is not None:
            cfg["commands"] = commands
        make_repo(d, cfg)
        with open(os.path.join(d, "a.txt"), "w", encoding="utf-8") as fh:
            fh.write("one\n")
        commit_all(d, "files")
        return d


