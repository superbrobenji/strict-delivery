class ConfigValueTest(Repo):
    def test_config_value_unset(self):  # GK1
        self.assertIsNone(gitinfo.config_value(self.repo(), "core.hooksPath"))

    def test_config_value_set(self):  # GK2
        d = self.repo()
        git(d, "config", "core.hooksPath", "/h")
        self.assertEqual(gitinfo.config_value(d, "core.hooksPath"), "/h")

    def test_config_value_empty(self):  # GK3
        d = self.repo()
        git(d, "config", "x.empty", "")
        append_config(d, "[x]\n\tbare\n")
        self.assertEqual(gitinfo.config_value(d, "x.empty"), "")
        self.assertEqual(gitinfo.config_value(d, "x.bare"), "")

    def test_config_value_last(self):  # GK4
        d = self.repo()
        git(d, "config", "--add", "x.dup", "1")
        git(d, "config", "--add", "x.dup", "2")
        self.assertEqual(gitinfo.config_value(d, "x.dup"), "2")

    def test_config_value_key_case(self):  # GK5
        d = self.repo()
        git(d, "config", "Core.HooksPath", "/h")
        self.assertEqual(gitinfo.config_value(d, "core.hookspath"), "/h")

    def test_config_value_newline(self):  # GK6
        d = self.repo()
        git(d, "config", "x.nl", "a\nb")
        self.assertEqual(gitinfo.config_value(d, "x.nl"), "a\nb")

    def test_config_value_bad_key(self):  # GK7
        d = self.repo()
        for key in ("", "nodot", "-x", "-x.y", "a.b\0c", "a.b\nc", b"core.x", _StrSub("core.x"), None):
            with self.subTest(key=repr(key)):
                with self.assertRaises(GateError) as cm:
                    gitinfo.config_value(d, key)
                self.assertIn("config key", str(cm.exception))

    def test_config_value_git_error_not_unset(self):  # GK7: git's exit 1 with an error is never "unset"
        d = self.repo()
        with self.assertRaises(GateError):
            gitinfo.config_value(d, "a.")

    def test_config_value_not_utf8(self):  # GK8
        d = self.repo()
        append_config(d, b"[x]\n\tbad = \xff\n")
        with self.assertRaises(GateError) as cm:
            gitinfo.config_value(d, "x.bad")
        self.assertIn("not valid UTF-8", str(cm.exception))

    def test_config_value_root_forms(self):  # GK9 (GI10-GI12)
        d = self.repo()
        git(d, "config", "x.k", "v")
        forms = helpers.root_forms(self.tmp, d)
        helpers.check_root_forms(self, forms, {"config_value": lambda r: gitinfo.config_value(r, "x.k")})
        for bad in ("", b"/x", _StrSub(d)):
            with self.subTest(root=type(bad).__name__):
                with self.assertRaises(GateError) as cm:
                    gitinfo.config_value(bad, "x.k")
                self.assertEqual(str(cm.exception), "root must be a string")
        with mock.patch.dict(os.environ, {"PATH": "/nonexistent-bin"}):
            with self.assertRaises(GitNotFound):
                gitinfo.config_value(d, "x.k")
        other = self.repo("r2")
        git(other, "config", "x.k", "other")
        with mock.patch.dict(os.environ, {"GIT_DIR": os.path.join(other, ".git")}):
            self.assertEqual(gitinfo.config_value(d, "x.k"), "v")

    def test_config_text_digits(self):  # V1d
        d = self.repo()
        git(d, "config", "x.n", "9" * 4301)
        self.assertEqual(gitinfo.config_value(d, "x.n"), "9" * 4301)


class ResultFunctionsTest(Repo):
    """GH1-GH4, GH8, GH11: the ``*_result`` functions of githooks."""

    def run_main(self, argv, stdin=b""):
        out = io.StringIO()
        with mock.patch.object(sys, "stdin", io.TextIOWrapper(io.BytesIO(stdin))), contextlib.redirect_stdout(out):
            code = githooks.main(argv)
        return code, out.getvalue()

    def test_status_result_lines(self):  # GH1
        d = self.repo()
        res = githooks.status_result(d, FRAMEWORK)
        self.assertEqual(res.render(False), "FAIL githooks.pre-commit: missing\nFAIL githooks.pre-push: missing\n")
        self.assertEqual(githooks.install(d, FRAMEWORK), [])
        self.assertEqual(githooks.status_result(d, FRAMEWORK).render(False),
                         "PASS githooks.pre-commit\nPASS githooks.pre-push\n")
        hooks = gitinfo.hooks_dir(d)
        with open(os.path.join(hooks, "pre-commit"), "ab") as fh:
            fh.write(b"# edit\n")
        with open(os.path.join(hooks, "pre-push"), "wb") as fh:
            fh.write(b"#!/bin/sh\nexit 0\n")
        os.chmod(os.path.join(hooks, "pre-push"), 0o755)
        self.assertEqual(githooks.status_result(d, FRAMEWORK).render(False),
                         "FAIL githooks.pre-commit: stale\nFAIL githooks.pre-push: foreign\n")
        empty = os.path.join(self.tmp, "emptyhooks")
        os.mkdir(empty)
        git(d, "config", "core.hooksPath", empty)
        self.assertEqual(githooks.status_result(d, FRAMEWORK).render(False),
                         "FAIL githooks.pre-commit: missing\nFAIL githooks.pre-push: missing\n")

    def test_status_result_equals_status(self):  # GH1
        d = self.repo()
        for step in ("missing", "installed"):
            with self.subTest(step):
                self.assertEqual(githooks.status_result(d, FRAMEWORK).render(False),
                                 githooks.status(d, FRAMEWORK).render(False))
                githooks.install(d, FRAMEWORK)

    def test_status_result_framework(self):  # GH2
        d = self.repo()
        for bad in ("relative/path", "", "/x\ny", "/x\x00y", b"/x", None, 3):
            with self.subTest(framework=repr(bad)):
                with self.assertRaises(GateError) as cm:
                    githooks.status_result(d, bad)
                self.assertEqual(str(cm.exception), githooks._FRAMEWORK)

    def test_pre_commit_result_matches_main(self):  # GH3
        d = self.repo(profile="standard")
        code, out = self.run_main(["pre-commit", "--root", d])
        self.assertEqual(code, 0)
        res = githooks.pre_commit_result(d)
        self.assertEqual(res.render(False), out)
        self.assertTrue(res.lines)
        self.assertNotIn("githook.test", out)

    def test_pre_commit_result_strict(self):  # GH4
        for label, commands, line in (
                ("passes", {"test": "true"}, "PASS githook.test\n"),
                ("fails", {"test": "exit 3"}, "FAIL githook.test: commands.test exited 3\n"),
                ("unset", None, "FAIL githook.test: commands.test is not set\n"),
                ("wrong type", {"test": 5}, "FAIL githook.test: %s\n" % githooks.TEST_TYPE)):
            with self.subTest(label):
                d = self.repo("s-" + label.replace(" ", "-"), profile="strict", commands=commands)
                code, out = self.run_main(["pre-commit", "--root", d])
                res = githooks.pre_commit_result(d)
                self.assertEqual(res.render(False), out)
                self.assertTrue(out.endswith(line), out)  # the test line comes last, after run_all's lines
                self.assertEqual(code, 0 if label == "passes" else 1)

    def test_pre_commit_result_flagged_and_unstaged(self):  # GH5
        d = self.repo(profile="standard")
        with open(os.path.join(d, "a.txt"), "w", encoding="utf-8") as fh:
            fh.write("two\n")
        git(d, "update-index", "--assume-unchanged", "a.txt")
        with open(os.path.join(d, "a.txt"), "w", encoding="utf-8") as fh:
            fh.write("three\n")
        code, out = self.run_main(["pre-commit", "--root", d])
        self.assertEqual(code, 1)
        self.assertEqual(githooks.pre_commit_result(d).render(False), out)
        self.assertTrue(out.startswith("FAIL githook.flagged: a.txt: "), out)

    def test_pre_commit_result_error_is_raised(self):  # GH7 (Q5 (ii) (a)): a GateError is raised, main converts it
        d = self.repo(profile="standard")
        sub = os.path.join(d, "sub")  # not a top level: gitinfo raises
        os.mkdir(sub)
        with self.assertRaises(GateError) as cm:
            githooks.pre_commit_result(sub)
        code, out = self.run_main(["pre-commit", "--root", sub])
        self.assertEqual(code, 1)
        self.assertEqual(out, "FAIL githook.input: %s\n" % cm.exception)
        with self.assertRaises(GateError):
            githooks.pre_push_result(sub, [])

    def test_pre_push_result_equals_main(self):  # GH8
        d = self.repo()
        head = git(d, "rev-parse", "HEAD")
        zeros = "0" * 40
        other = "1" * 40
        for label, updates in (
                ("empty", []),
                ("base", [("refs/heads/feat", head, "refs/heads/main")]),
                ("deletion of base", [("(delete)", zeros, "refs/heads/main")]),
                ("sha not HEAD", [("refs/heads/feat", other, "refs/heads/feat")]),
                ("deletion elsewhere", [("(delete)", zeros, "refs/heads/feat")])):
            with self.subTest(label):
                stdin = "".join("%s %s %s %s\n" % (ref, sha, remote, zeros) for ref, sha, remote in updates)
                code, out = self.run_main(["pre-push", "--root", d, "origin", "url"], stdin.encode("utf-8"))
                res = githooks.pre_push_result(d, updates)
                self.assertEqual(res.render(False), out)
                self.assertEqual(code, 0 if res.ok() else 1)
        res = githooks.pre_push_result(d, [("refs/heads/feat", head, "refs/heads/main")])
        self.assertEqual(res.render(False), "FAIL githook.base: main is protected; open a pull request\n")

    def test_result_functions_print_nothing(self):  # GH6, GH11
        d = self.repo(profile="strict", commands={"test": "echo noise-out; echo noise-err >&2"})
        script = os.path.join(self.tmp, "call.py")
        with open(script, "w", encoding="utf-8") as fh:
            fh.write("import sys\n"
                     "from gates.tools import githooks\n"
                     "sys.stderr.write(githooks.pre_commit_result(sys.argv[1]).render(False))\n"
                     "sys.stderr.write(githooks.pre_push_result(sys.argv[1], []).render(False))\n"
                     "sys.stderr.write(githooks.status_result(sys.argv[1], githooks.framework_dir()).render(False))\n")
        env = dict(os.environ, PYTHONPATH=SRC)
        p = subprocess.run([sys.executable, script, d], cwd=SRC, env=env, stdin=subprocess.DEVNULL,
                           stdout=subprocess.PIPE, stderr=subprocess.PIPE)
        self.assertEqual(p.returncode, 0, p.stderr)
        self.assertEqual(p.stdout, b"")  # not even the test command's own output reaches fd 1
        err = p.stderr.decode("utf-8")
        self.assertNotIn("noise", err)
        self.assertIn("PASS githook.test\n", err)
        _, main_out = self.run_main(["pre-commit", "--root", d])
        self.assertTrue(main_out.endswith("PASS githook.test\n"))

    def test_main_prints_test_output_between_lines(self):  # GH9: main keeps the child's output where it was
        d = self.repo(profile="strict", commands={"test": "echo noise-out"})
        env = dict(os.environ, PYTHONPATH=SRC)
        p = subprocess.run([sys.executable, "-m", "gates", "githook", "pre-commit", "--root", d], cwd=SRC, env=env,
                           stdin=subprocess.DEVNULL, stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
        out = p.stdout.decode("utf-8")
        self.assertEqual(p.returncode, 0, out)
        self.assertTrue(out.endswith("noise-out\nPASS githook.test\n"), out)


