class Recorder:
    def __init__(self, fails=()):
        self.calls = []
        self.fails = fails

    def __call__(self, root):
        self.calls.append(root)
        res = Result("g")
        res.passed("a.pass")
        for gid, why in self.fails:
            res.fail(gid, why)
        return res


