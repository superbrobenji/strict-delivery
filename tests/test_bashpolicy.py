def append_config(root, text):
    with open(os.path.join(root, ".git", "config"), "ab") as fh:
        fh.write(text if isinstance(text, bytes) else text.encode("utf-8"))


class Repo(GitIsolatedTestCase):
    def repo(self, name="r", profile=None, commands=None):
        d = os.path.join(self.tmp, name)
        os.mkdir(d)
        cfg = minimal_config()
        if profile:
            cfg["profile"] = profile
        if commands is not None:
            cfg["commands"] = commands
        make_repo(d, cfg)
        with open(os.path.join(d, "a.txt"), "w", encoding="utf-8") as fh:
            fh.write("one\n")
        commit_all(d, "files")
        return d


class AliasesTest(Repo):
    def test_aliases_none(self):  # GI1
        self.assertEqual(gitinfo.aliases(self.repo()), {})

    def test_aliases_one(self):  # GI2
        d = self.repo()
        git(d, "config", "alias.ci", "commit")
        self.assertEqual(gitinfo.aliases(d), {"ci": "commit"})

    def test_aliases_value_newline(self):  # GI3
        d = self.repo()
        git(d, "config", "alias.ml", "commit -m 'a\nb'")
        self.assertEqual(gitinfo.aliases(d), {"ml": "commit -m 'a\nb'"})

    def test_aliases_shell(self):  # GI4
        d = self.repo()
        git(d, "config", "alias.x", "!git commit")
        self.assertEqual(gitinfo.aliases(d), {"x": "!git commit"})

    def test_aliases_name_lowercase(self):  # GI5
        d = self.repo()
        git(d, "config", "alias.Cx", "!git commit")
        self.assertEqual(gitinfo.aliases(d), {"cx": "!git commit"})

    def test_aliases_empty_and_valueless(self):  # GI6
        d = self.repo()
        git(d, "config", "alias.e", "")
        append_config(d, "[alias]\n\tv\n")
        self.assertEqual(gitinfo.aliases(d), {"e": "", "v": ""})

    def test_aliases_duplicate_last_wins(self):  # GI7
        d = self.repo()
        git(d, "config", "--add", "alias.dup", "commit")
        git(d, "config", "--add", "alias.dup", "push")
        self.assertEqual(gitinfo.aliases(d), {"dup": "push"})

    def test_aliases_not_utf8(self):  # GI8
        d = self.repo()
        append_config(d, b"[alias]\n\tbad = \xff\n")
        with self.assertRaises(GateError) as cm:
            gitinfo.aliases(d)
        self.assertIn("config", str(cm.exception))
        self.assertIn("not valid UTF-8", str(cm.exception))

    def test_aliases_sources(self):  # GI9
        d = self.repo()
        glob = os.path.join(self.tmp, "global.cfg")
        with open(glob, "w", encoding="utf-8") as fh:
            fh.write("[alias]\n\tg = from-global\n\tboth = global-value\n")
        git(d, "config", "alias.l", "from-local")
        git(d, "config", "alias.both", "local-value")
        with mock.patch.dict(os.environ, {"GIT_CONFIG_GLOBAL": glob}):
            self.assertEqual(gitinfo.aliases(d), {"g": "from-global", "l": "from-local", "both": "local-value"})

    def test_aliases_root_forms(self):  # GI10
        d = self.repo()
        forms = helpers.root_forms(self.tmp, d)
        helpers.check_root_forms(self, forms, {"aliases": gitinfo.aliases})
        for bad in ("", b"/x", _StrSub(d)):
            with self.subTest(root=type(bad).__name__):
                with self.assertRaises(GateError) as cm:
                    gitinfo.aliases(bad)
                self.assertEqual(str(cm.exception), "root must be a string")

    def test_aliases_git_missing(self):  # GI11
        d = self.repo()
        with mock.patch.dict(os.environ, {"PATH": "/nonexistent-bin"}):
            with self.assertRaises(GitNotFound):
                gitinfo.aliases(d)

    def test_aliases_env_cleared(self):  # GI12
        d = self.repo("r1")
        other = self.repo("r2")
        git(other, "config", "alias.zz", "other-repo")
        git(d, "config", "alias.here", "this-repo")
        with mock.patch.dict(os.environ, {"GIT_DIR": os.path.join(other, ".git")}):
            self.assertEqual(gitinfo.aliases(d), {"here": "this-repo"})

    def test_aliases_format(self):  # V6: one output format on the installed git
        d = self.repo()
        git(d, "config", "alias.a", "log --oneline")
        git(d, "config", "alias.b", "!echo 'x y'")
        self.assertEqual(gitinfo.aliases(d), {"a": "log --oneline", "b": "!echo 'x y'"})

    def test_config_text_digits(self):  # V1d: a 4301-digit value is text; int() is never called
        d = self.repo()
        git(d, "config", "alias.n", "9" * 4301)
        self.assertEqual(gitinfo.aliases(d), {"n": "9" * 4301})


