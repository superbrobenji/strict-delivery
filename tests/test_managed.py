class FsCase(GitIsolatedTestCase, Base):
    def setUp(self):
        super().setUp()
        self.r = make_repo(self.work)

    def path(self, rel):
        return os.path.join(self.r, *rel.split("/"))

    def put_file(self, rel, data, mode=None):
        p = self.path(rel)
        os.makedirs(os.path.dirname(p), exist_ok=True)
        with open(p, "wb") as fh:
            fh.write(data if isinstance(data, bytes) else data.encode("utf-8"))
        if mode is not None:
            os.chmod(p, mode)
        return p

    def read(self, rel):
        with open(self.path(rel), "rb") as fh:
            return fh.read().decode("utf-8")

    def snapshot(self):
        res = []
        for d, ds, fs in os.walk(self.r):
            if ".git" in d.split(os.sep):
                continue
            for n in sorted(ds + fs):
                p = os.path.join(d, n)
                st = os.lstat(p)
                res.append((p, st.st_mode, st.st_mtime_ns, st.st_size))
        return sorted(res)

    def needs_unprivileged(self):
        if os.geteuid() == 0:
            self.skipTest("root ignores directory and file modes")

    def writable_cleanup(self, p):
        self.addCleanup(os.chmod, p, 0o755)


