class Base(unittest.TestCase):
    def me(self, msg, fn, *a, **k):
        with self.assertRaises(ManagedError) as c:
            fn(*a, **k)
        self.assertIs(type(c.exception), ManagedError)
        self.assertIsInstance(c.exception, GateError)
        self.assertEqual(str(c.exception), msg)
        return c.exception

    def vmb(self, text, style=HTML):
        return schema.validate_managed_block(CBS if style == HTML else GBS, text)


