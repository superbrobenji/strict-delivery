def out(text):
    """(before, after) of the one html block of ``text``, hand-written (never managed)."""
    ls = text.split("\n")
    b = [i for i, x in enumerate(ls) if x.startswith("<!-- strict-delivery:begin")]
    e = [i for i, x in enumerate(ls) if x == E]
    return "\n".join(ls[:b[0]]), "\n".join(ls[e[0] + 1:])


