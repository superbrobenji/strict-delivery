class SourceTests(Base):
    def tree(self):
        with open(os.path.join(ROOT, "gates", "lib", "managed.py"), encoding="utf-8") as fh:
            return ast.parse(fh.read())

    def test_managed_imports(self):  # PV6
        allowed = {"__future__", "errno", "os", "re", "stat", "tempfile", "dataclasses", "typing", "gates.lib.result"}
        for node in ast.walk(self.tree()):
            if isinstance(node, ast.Import):
                for a in node.names:
                    self.assertIn(a.name, allowed)
            elif isinstance(node, ast.ImportFrom):
                self.assertIn(node.module, allowed)

    def test_managed_makes_no_git_call(self):  # AP39, PV6
        for node in ast.walk(self.tree()):
            if isinstance(node, ast.Name):
                self.assertNotIn(node.id, ("subprocess", "gitinfo"))
            if isinstance(node, ast.Attribute):
                self.assertNotIn(node.attr, ("system", "popen", "run", "Popen", "call", "check_output"))

    def test_no_unicode_dependent_calls(self):  # PV2
        banned = {"lower", "upper", "casefold", "isprintable", "isdigit", "isalpha", "isspace", "isnumeric",
                  "isalnum", "isdecimal", "isidentifier", "unicodedata", "IGNORECASE", "ASCII", "int", "splitlines"}
        for node in ast.walk(self.tree()):
            if isinstance(node, ast.Attribute):
                self.assertNotIn(node.attr, banned)
            if isinstance(node, ast.Name) and node.id != "int":
                self.assertNotIn(node.id, banned)
            if isinstance(node, ast.Call) and isinstance(node.func, ast.Name):
                self.assertNotEqual(node.func.id, "int")
            if isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute) and node.func.attr in (
                    "strip", "lstrip", "rstrip"):
                self.assertTrue(node.args)
        with open(os.path.join(ROOT, "gates", "lib", "managed.py"), encoding="utf-8") as fh:
            src = fh.read()
        for needle in ("\\d", "\\w", "\\s"):
            self.assertNotIn("[" + needle, src)
            self.assertNotIn(r'r"' + needle, src)

    def test_no_exception_groups(self):  # PV3
        for rel in ("gates/lib/managed.py", "tests/test_managed.py"):
            with open(os.path.join(ROOT, rel), encoding="utf-8") as fh:
                tree = ast.parse(fh.read())
            for node in ast.walk(tree):
                self.assertNotEqual(type(node).__name__, "TryStar", rel)
                if isinstance(node, ast.Name):
                    self.assertNotIn(node.id, ("ExceptionGroup", "BaseExceptionGroup"), rel)

