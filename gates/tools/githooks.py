"""Tool ``githooks`` and the command ``githook``: the git hook shims, what they run, and the installer
(spec 4, 13; plan Task 2b.2; owner Q-B2plan-11 (a), Q-B2plan-12 (a), Q-B2plan-13 (a), F-3).

``python3 -m gates githook <pre-commit|pre-push> --root R [git's args]`` (``main``) is what a shim execs:
``pre-commit`` refuses a tracked file with unstaged changes before any gate runs, runs ``run_all`` and, on the strict
profile, ``commands.test``; ``pre-push`` refuses a tree with any tracked change or a pushed sha other than ``HEAD``
(a deletion is allowed) or a push whose remote ref is ``refs/heads/<base_branch>`` (``githook.base``: open a pull
request), then runs ``run_all``. ``python3 -m gates githooks <install|status> [--root R]``
(``manage``) writes and checks the two shims. The root is always the ``--root`` value; ``CLAUDE_PROJECT_DIR`` is
never read, and every git call runs with ``-C root`` (``gitinfo``), so a relative ``GIT_INDEX_FILE`` stays the
target's after the shim's ``cd``. Standard library only.
"""
from __future__ import annotations

import os
import re
import stat
import subprocess
import sys
import tempfile
from typing import List, Optional

from gates import run_all
from gates.lib import config, gitinfo, result
from gates.lib.result import GateError, Line, Result

NAMES = ("pre-commit", "pre-push")
HEADER = "# strict-delivery: generated by python3 -m gates githooks install; do not edit"
HOOK_USAGE = "usage: python3 -m gates githook <pre-commit|pre-push> --root R [git's args]\n"
MANAGE_USAGE = "usage: python3 -m gates githooks <install|status> [--root R]\n"
UNSTAGED = "tracked file has unstaged changes; stage it or stash it, so the gates read the tree being committed"
FLAGGED = ("tracked file is flagged assume-unchanged or skip-worktree; clear the flag with git update-index so the "
           "gates read the work tree")
TEST_TYPE = "commands.test must be a non-empty string or a non-empty list of non-empty strings"
_SHA = re.compile(r"(?:[0-9a-f]{40}|[0-9a-f]{64})")
_UNSET = object()
_FRAMEWORK = "the framework path must be absolute and hold no control character"


class _FrameworkError(GateError):
    """The framework path cannot be written into a shim."""


def framework_dir() -> str:
    """The directory holding the ``gates`` package, with symlinks resolved."""
    return os.path.dirname(os.path.dirname(os.path.dirname(os.path.realpath(__file__))))


# ---- shims ----------------------------------------------------------------------------------------------------
def _check_framework(framework: object) -> None:
    if (type(framework) is not str or not os.path.isabs(framework)
            or any(ord(c) < 32 or ord(c) == 127 for c in framework)):
        raise _FrameworkError(_FRAMEWORK)


def _quote(path: str) -> str:
    """``path`` in POSIX single quotes, a ``'`` inside as ``'"'"'``: ``/bin/sh`` reads it literally."""
    return "'" + path.replace("'", "'\"'\"'") + "'"


def shim(name: str, framework: str) -> bytes:
    """The three lines of a hook file (Q-B2plan-13 (a)); the path's bytes are the file system's own."""
    text = ("#!/bin/sh\n%s\ncd %s && exec python3 -m gates githook %s --root \"$OLDPWD\" \"$@\"\n"
            % (HEADER, _quote(framework), name))
    return os.fsencode(text)


def _state(path: str, expected: bytes) -> str:
    """``ok``, ``missing``, ``foreign`` (not a regular file, or no header on line 2) or ``stale`` (own header, other
    bytes or mode)."""
    try:
        st = os.lstat(path)
    except (FileNotFoundError, NotADirectoryError):
        return "missing"
    except OSError:
        return "foreign"
    if not stat.S_ISREG(st.st_mode):
        return "foreign"
    try:
        with open(path, "rb") as fh:
            data = fh.read()
    except OSError:
        return "foreign"
    lines = data.split(b"\n")
    if len(lines) < 2 or lines[1] != HEADER.encode("ascii"):
        return "foreign"
    if data != expected or stat.S_IMODE(st.st_mode) != 0o755:
        return "stale"
    return "ok"


def _write(path: str, data: bytes) -> None:
    """Write ``data`` to a temporary file in the hook's directory, then ``os.replace`` it: mode 0o755 at once."""
    fd, tmp = tempfile.mkstemp(prefix=".sd-hook-", dir=os.path.dirname(path))
    try:
        with os.fdopen(fd, "wb") as fh:
            fh.write(data)
        os.chmod(tmp, 0o755)
        os.replace(tmp, path)
    except BaseException:
        try:
            os.unlink(tmp)
        except OSError:
            pass
        raise


def _hooks_path(root: str) -> Optional[str]:
    """The value of ``core.hooksPath`` from any config source (``None`` when unset; ``""`` when set empty)."""
    p = gitinfo._run(root, "config core.hooksPath", ["config", "--null", "--get", "core.hooksPath"], ok=(0, 1))
    if p.returncode == 1:
        return None
    return gitinfo._text(p.stdout, "config").rstrip("\0")


def install(root: str, framework: str) -> list:
    """Write ``pre-commit`` and ``pre-push`` into ``hooks_dir(root)``. Returns the FAIL lines (``Line``) of every
    conflict, writing nothing: ``githooks.hooks-path`` when ``core.hooksPath`` is set (any value), and
    ``githooks.<name>: foreign`` for a file without the header; a write error is one ``githooks.write`` line.
    ``[]`` means both files are written and current. A bad framework path or root is a GateError."""
    _check_framework(framework)
    hooks = gitinfo.hooks_dir(root)
    fails: List[Line] = []
    value = _hooks_path(root)
    if value is not None:
        fails.append(Line("FAIL", "githooks.hooks-path",
                          "core.hooksPath is set (%s); unset it to install the hooks" % value))
    for name in NAMES:
        if _state(os.path.join(hooks, name), shim(name, framework)) == "foreign":
            fails.append(Line("FAIL", "githooks." + name, "foreign"))
    if fails:
        return fails
    for name in NAMES:
        path = os.path.join(hooks, name)
        try:
            os.makedirs(hooks, exist_ok=True)
            _write(path, shim(name, framework))
        except OSError as e:
            return [Line("FAIL", "githooks.write", "%s: %s" % (path, e.strerror or type(e).__name__))]
    return []


def status(root: str, framework: str) -> Result:
    """``PASS githooks.<name>`` or ``FAIL githooks.<name>: missing | foreign | stale`` for each hook."""
    _check_framework(framework)
    hooks = gitinfo.hooks_dir(root)
    res = Result("githooks")
    for name in NAMES:
        state = _state(os.path.join(hooks, name), shim(name, framework))
        if state == "ok":
            res.passed("githooks." + name)
        else:
            res.fail("githooks." + name, state)
    return res


def _flags(args: List[str]) -> Optional[tuple]:
    """``(root or None, rest)`` for the leading ``--root R`` / ``--root=R`` of ``args`` (at most one); ``None`` for a
    usage error (a missing value, or ``--root`` twice)."""
    root = None
    i = 0
    while i < len(args):
        a = args[i]
        if a == "--root":
            if root is not None or i + 1 >= len(args):
                return None
            root = args[i + 1]
            i += 2
        elif a.startswith("--root="):
            if root is not None:
                return None
            root = a[len("--root="):]
            i += 1
        else:
            break
    return root, args[i:]


def manage(argv: List[str]) -> int:
    """``python3 -m gates githooks <install|status> [--root R]``: 0 when every line passes, 1 otherwise, 2 for usage."""
    parsed = _flags(argv[1:]) if argv and argv[0] in ("install", "status") else None
    if parsed is None or parsed[1]:
        sys.stderr.write(MANAGE_USAGE)
        return 2
    try:
        root = parsed[0]
        if root == "":
            raise GateError("--root must not be empty")
        if root is None:
            root = result.repo_root()
        framework = framework_dir()
        if argv[0] == "status":
            res = status(root, framework)
        else:
            fails = install(root, framework)
            res = Result("githooks", fails)
            if not fails:
                for name in NAMES:
                    res.passed("githooks." + name)
    except _FrameworkError as e:
        res = Result("githooks")
        res.fail("githooks.framework", str(e))
    except GateError as e:
        res = Result("githooks")
        res.fail("githooks.input", str(e))
    sys.stdout.write(res.render(False))
    return 0 if res.ok() else 1


# ---- the hooks ------------------------------------------------------------------------------------------------
def _parse_hook(argv: List[str]) -> Optional[tuple]:
    """``(name, root)`` when the arguments are ``<name> --root R`` and, for ``pre-push``, git's two (the remote's name
    and url, which nothing reads); ``None`` for a usage error."""
    if not argv or argv[0] not in NAMES:
        return None
    parsed = _flags(argv[1:])
    if parsed is None or parsed[0] is None:
        return None
    if len(parsed[1]) != (0 if argv[0] == "pre-commit" else 2):  # pre-push: the remote's name and url
        return None
    return argv[0], parsed[0]


def _gates(root: str) -> Result:
    """``run_all.check(["--root", root])`` as the gate contract runs it; a gate run that raises is one
    ``githook.run_all`` line."""
    res = result.run_check("run_all", run_all.check, ["--root", root])
    return Result("githook", [Line("FAIL", "githook.run_all", ln.reason) if ln.id == "run_all.input" else ln
                              for ln in res.lines])


def _run_commands_test(root: str, cfg: dict) -> Line:
    """Run ``commands.test`` in ``root`` (Q-B2plan-11 (a)): a string with ``sh -c``, a list as one argv."""
    commands = cfg.get("commands")
    test = commands.get("test", _UNSET) if type(commands) is dict else _UNSET
    if test is _UNSET:
        return Line("FAIL", "githook.test", "commands.test is not set")
    if type(test) is str and test != "":
        argv = ["sh", "-c", test]
    elif type(test) is list and test and all(type(a) is str and a != "" for a in test):
        argv = list(test)
    else:
        return Line("FAIL", "githook.test", TEST_TYPE)
    env = {k: v for k, v in os.environ.items() if k not in gitinfo.CLEARED_ENV and k != "GIT_INDEX_FILE"}
    sys.stdout.flush()  # run_all's lines come before the command's output
    try:
        p = subprocess.run(argv, cwd=root, env=env, stdin=subprocess.DEVNULL, check=False)
    except (OSError, ValueError) as e:
        return Line("FAIL", "githook.test", "commands.test could not run: %s" % result._exc_text(e))
    if p.returncode != 0:
        return Line("FAIL", "githook.test", "commands.test exited %d" % p.returncode)
    return Line("PASS", "githook.test")


def _staged_paths(root: str) -> List[str]:
    p = gitinfo._run(root, "diff --cached --name-only",
                     ["diff", "--cached", "--no-color", "--name-only", "-z", "--no-ext-diff", "--no-textconv",
                      "--ignore-submodules=none"], opts=gitinfo.FSMONITOR_OFF)
    return [gitinfo._text(raw, "diff --cached --name-only") for raw in p.stdout.split(b"\0") if raw]


def _updates(data: bytes) -> list:
    """The ``(local ref, local sha, remote ref)`` of each line git gives a pre-push hook on stdin (``<local ref> <local sha>
    <remote ref> <remote sha>``); a trailing empty line is ignored; anything else malformed is a GateError."""
    lines = data.split(b"\n")
    while lines and lines[-1] == b"":
        lines.pop()
    out = []
    for n, raw in enumerate(lines, 1):
        try:
            fields = raw.decode("utf-8").split(" ")
        except UnicodeDecodeError:
            raise GateError("pre-push line %d: not valid UTF-8" % n) from None
        if len(fields) != 4:
            raise GateError("pre-push line %d: expected 4 fields, found %d" % (n, len(fields)))
        for i in (1, 3):
            if fields[i - 1] == "":
                raise GateError("pre-push line %d: field %d is empty" % (n, i))
        for i in (2, 4):
            if not _SHA.fullmatch(fields[i - 1]):
                raise GateError("pre-push line %d: field %d is not a lowercase hex sha of 40 or 64 digits" % (n, i))
        out.append((fields[0], fields[1], fields[2]))
    return out


def _base_lines(base: str, updates: list) -> list:
    """One ``githook.base`` FAIL line per update whose remote ref is exactly ``refs/heads/<base>`` (Task P3.1, owner
    directive: the base branch changes through a pull request only; a deletion is a push to it too). Stdin and the
    configured name only, no git call. Stated limit (D-Q5): ``git push --mirror`` sends no line for a remote branch it
    deletes, so the hook cannot see that; host branch protection covers it."""
    target = "refs/heads/" + base
    return [Line("FAIL", "githook.base", "%s is protected; open a pull request" % base)
            for _local, _sha, remote in updates if remote == target]


def _flagged_lines(root: str) -> list:
    """One ``githook.flagged`` FAIL line per tracked path flagged assume-unchanged or skip-worktree (Q-G1-3 (a)):
    ``git diff`` cannot show a change to such a path, so the gates would read a tree the commit does not hold."""
    return [Line("FAIL", "githook.flagged", "%s: %s" % (path, FLAGGED)) for path in gitinfo.flagged_paths(root)]


def _pre_commit(root: str) -> int:
    unstaged = [Line("FAIL", "githook.unstaged", "%s: %s" % (path, UNSTAGED)) for path in gitinfo.unstaged_paths(root)]
    lines = _flagged_lines(root) + unstaged  # D-14: the flagged lines, then the unstaged lines, then no gate
    if lines:
        return _report(Result("githook", lines))
    res = _gates(root)
    sys.stdout.write(res.render(False))  # run_all's lines first, then any commands.test line
    if not res.ok():
        return 1
    cfg = config.load(root)
    if cfg["profile"] != "strict":
        return 0
    return _report(Result("githook", [_run_commands_test(root, cfg)]))


def _pre_push(root: str, stdin: bytes) -> int:
    head = gitinfo.head_sha(root)
    updates = _updates(stdin)
    base = config.load(root)["base_branch"]
    changed = _staged_paths(root)
    changed += [p for p in gitinfo.unstaged_paths(root) if p not in changed]
    lines = _flagged_lines(root)  # D-14: the flagged lines, then the dirty lines, then the push-sha lines
    lines += [Line("FAIL", "githook.dirty", "%s: tracked file has a change; commit it before pushing" % p)
              for p in changed]
    for ref, sha, _remote in updates:
        if sha != head and sha != "0" * len(sha):  # an all-zero local sha is a deletion
            lines.append(Line("FAIL", "githook.push-sha",
                              "%s: pushes %s, not HEAD %s; check out the branch to push it" % (ref, sha, head)))
    lines += _base_lines(base, updates)  # D-Q4: after the flagged, dirty and push-sha lines
    if lines:
        return _report(Result("githook", lines))
    return _report(_gates(root))


def _report(res: Result) -> int:
    sys.stdout.write(res.render(False))
    return 0 if res.ok() else 1


def main(argv: List[str]) -> int:
    """``python3 -m gates githook <pre-commit|pre-push> --root R [git's args]``: 0 when every line passes."""
    parsed = _parse_hook(argv)
    if parsed is None:
        sys.stderr.write(HOOK_USAGE)
        return 2
    name, root = parsed
    try:
        if root == "":
            raise GateError("--root must not be empty")
        root = os.path.abspath(root)  # a relative root is the caller's directory; never read as an option
        stdin = sys.stdin.buffer.read() if name == "pre-push" else b""
        return _pre_commit(root) if name == "pre-commit" else _pre_push(root, stdin)
    except GateError as e:
        res = Result("githook")
        res.fail("githook.input", str(e))
        return _report(res)
