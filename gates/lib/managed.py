"""Managed blocks, the generated-file header and the no-overwrite write planner (standard library and ``result`` only).

A managed block is the text between two marker lines in ``CLAUDE.md`` (html comments) or ``.gitignore`` (hash
comments); the text outside the markers is never changed. ``plan`` lists the writes ``init`` and ``upgrade`` would make
and every conflict (a path that exists and is not framework-managed, a symlink, a parent that is not a directory, a
malformed block, two writes to one path); ``apply`` writes through a temporary file and ``os.replace``. Lines split on
``"\\n"`` only; every character class is an explicit ASCII range, never a Unicode-version-dependent call."""
from __future__ import annotations

import errno
import os
import re
import stat
from dataclasses import dataclass
from typing import Optional

from gates.lib.result import GateError

HTML = "html"
HASH = "hash"

# kind -> schema number (the schema files hold the same; a test compares them) and the file and style of its block
KINDS = {"claude-block": 1, "gitignore-block": 1}
_KIND_FILE = {"claude-block": "CLAUDE.md", "gitignore-block": ".gitignore"}
_KIND_STYLE = {"claude-block": HTML, "gitignore-block": HASH}

_OPENER = {HTML: "<!-- ", HASH: "# "}
_CLOSER = {HTML: " -->", HASH: ""}
_BOM = "\N{ZERO WIDTH NO-BREAK SPACE}"
_KIND_RE = re.compile(r"[a-z][a-z-]*")
_VERSION_RE = re.compile(r"[0-9]+\.[0-9]+\.[0-9]+")
_BEGIN_TAIL = r"strict-delivery:begin schema=([a-z][a-z-]*)/(0|[1-9][0-9]{0,599}) version=([0-9]+\.[0-9]+\.[0-9]+)"
_BEGIN_RE = {s: re.compile(re.escape(_OPENER[s]) + _BEGIN_TAIL + re.escape(_CLOSER[s])) for s in (HTML, HASH)}

HEADER_RE = re.compile(r"# strict-delivery: generated by [^;\n]+; do not edit")

_NOT_MANAGED = "exists and is not framework-managed"
_WRITE_KINDS = ("file", "claude-block", "gitignore-block")
_PATH_MSG = "path: must be a relative path inside the root"


class ManagedError(GateError):
    """A bad argument, an unsafe path, a malformed block or a failed write."""


def _str(value: object, what: str) -> str:
    if type(value) is not str:
        raise ManagedError("%s: must be a string" % what)
    return value


def _check_style(style: object) -> str:
    _str(style, "style")
    if style != HTML and style != HASH:
        raise ManagedError('style: must be "html" or "hash"')
    return style


def _check_kind(kind: object) -> str:
    _str(kind, "kind")
    if _KIND_RE.fullmatch(kind) is None:
        raise ManagedError("kind: must match [a-z][a-z-]*")
    if kind not in KINDS:
        raise ManagedError("kind: unknown block kind")
    return kind


def _check_version(version: object) -> str:
    _str(version, "version")
    if _VERSION_RE.fullmatch(version) is None:
        raise ManagedError("version: must match [0-9]+\\.[0-9]+\\.[0-9]+")
    return version


def begin_marker(style: str, kind: str, version: str) -> str:
    _check_style(style)
    _check_kind(kind)
    _check_version(version)
    return "%sstrict-delivery:begin schema=%s/%d version=%s%s" % (_OPENER[style], kind, KINDS[kind], version,
                                                                   _CLOSER[style])


def end_marker(style: str) -> str:
    _check_style(style)
    return _OPENER[style] + "strict-delivery:end" + _CLOSER[style]


@dataclass(frozen=True)
class Block:
    begin: int  # 0-based line index of the begin marker
    end: int  # 0-based line index of the end marker
    kind: str
    version: str
    body: str  # the text between the two marker lines, each line with its "\n"


def _parse(text: str, style: str):
    """``None`` for a text with no marker-like line, else ``(begin, end, kind, n, version, lines)``; raises
    ``ManagedError`` with the structural reason otherwise (the order of the 4a.1 list: first malformed begin, first
    malformed end, more than one begin, no end, end before begin, more than one end)."""
    begin_like = _OPENER[style] + "strict-delivery:begin"
    end_like = _OPENER[style] + "strict-delivery:end"
    end_exact = end_like + _CLOSER[style]
    lines = text.split("\n")
    begins: list = []
    ends: list = []
    for i, line in enumerate(lines):
        probe = line[1:] if i == 0 and line.startswith(_BOM) else line
        probe = probe.lstrip(" \t")
        if probe.startswith(begin_like):
            begins.append((i, _BEGIN_RE[style].fullmatch(line)))
        elif probe.startswith(end_like):
            ends.append((i, line == end_exact))
    if not begins and not ends:
        return None
    for i, m in begins:
        if m is None:
            raise ManagedError("block: begin marker malformed: line %d" % (i + 1))
    for i, exact in ends:
        if not exact:
            raise ManagedError("block: end marker malformed: line %d" % (i + 1))
    if len(begins) > 1:
        raise ManagedError("block: more than one begin marker")
    if not ends:
        raise ManagedError("block: no end marker")
    if not begins or ends[0][0] < begins[0][0]:
        raise ManagedError("block: end marker before begin marker: line %d" % (ends[0][0] + 1))
    if len(ends) > 1:
        raise ManagedError("block: more than one end marker")
    m = begins[0][1]
    return begins[0][0], ends[0][0], m.group(1), m.group(2), m.group(3), lines


def find_block(text: str, style: str) -> Optional[Block]:
    """The block in ``text``, ``None`` when the text has no marker-like line; ``ManagedError`` with the Task 4a.1
    structural reason otherwise (the ``schema:`` tag compare is the schema gate's, never raised here)."""
    if type(text) is not str:
        raise ManagedError("block: text must be a string")
    _check_style(style)
    p = _parse(text, style)
    if p is None:
        return None
    b, e, kind, _n, version, lines = p
    return Block(b, e, kind, version, "".join(line + "\n" for line in lines[b + 1:e]))


def _check_body(body: object, style: str) -> str:
    _str(body, "body")
    if not body.endswith("\n"):
        raise ManagedError("body: must end in a newline")
    marker_like = (_OPENER[style] + "strict-delivery:begin", _OPENER[style] + "strict-delivery:end")
    for k, line in enumerate(body.split("\n")[:-1], 1):
        if line.lstrip(" \t").startswith(marker_like):
            raise ManagedError("body: holds a marker-like line: line %d" % k)
    return body


def _put(text: str, style: str, kind: str, version: str, body: str) -> str:
    p = _parse(text, style)
    marker, end = begin_marker(style, kind, version), end_marker(style)
    if p is None:
        if text != "" and not text.endswith("\n"):
            text += "\n"
        return text + marker + "\n" + body + end + "\n"
    b, e, got_kind, got_n, _v, lines = p
    if got_kind != kind:
        raise ManagedError("schema: expected %s/%d, got %s/%s; run /strict-delivery:upgrade"
                           % (kind, KINDS[kind], got_kind, got_n))
    out = "".join(line + "\n" for line in lines[:b]) + marker + "\n" + body + end
    if e != len(lines) - 1:
        out += "\n" + "\n".join(lines[e + 1:])
    return out


def put_block(text: Optional[str], style: str, kind: str, version: str, body: str) -> str:
    """``text`` with the block of ``kind`` set: a new text for ``None``, appended when there is no block, else the
    marker and body of the one block replaced. The text outside the markers is byte-identical."""
    _check_style(style)
    _check_kind(kind)
    _check_version(version)
    _check_body(body, style)
    if text is None:
        text = ""
    elif type(text) is not str:
        raise ManagedError("block: text must be a string")
    return _put(text, style, kind, version, body)


def is_generated(text: str) -> bool:
    """True when line 1 is the generated-file header, or line 1 starts with ``#!`` and line 2 is the header."""
    _str(text, "text")
    lines = text.split("\n")
    if HEADER_RE.fullmatch(lines[0]) is not None:
        return True
    return lines[0].startswith("#!") and len(lines) > 1 and HEADER_RE.fullmatch(lines[1]) is not None


@dataclass(frozen=True)
class Write:
    path: str
    text: str
    kind: str  # "file" (whole file), "claude-block" or "gitignore-block" (text is then the block body)


def _check_root(root: object) -> str:
    _str(root, "root")
    if root == "" or not os.path.isdir(root):
        raise ManagedError("root: not a directory")
    return root


def _check_path(path: object) -> str:
    if type(path) is not str:
        raise ManagedError("path: must be a string")
    bad = (path == "" or path.startswith("/") or path.startswith("~") or ":" in path or "\\" in path
           or path.replace(" ", "") == "")
    if not bad:
        for c in path:
            if c < " " or c > "~":
                bad = True
                break
    if not bad and any(part in ("", ".", "..") for part in path.split("/")):
        bad = True
    if bad:
        raise ManagedError(_PATH_MSG)
    return path


def _encodable(path: str, text: str) -> None:
    try:
        text.encode("utf-8")
    except UnicodeEncodeError:
        raise ManagedError("%s: text is not encodable as UTF-8" % path) from None


_DIR_FLAGS = os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW


class _NotDirectory(Exception):
    """A parent component is not a directory (a symlink, a file or a FIFO); the text is its path below the root."""


def _open_parents(root: str, parents: list, create: bool) -> int:
    """The descriptor of the directory ``parents`` below ``root``: ``root`` is opened ``O_DIRECTORY``, then each
    component from the descriptor of the one before (``dir_fd``, ``O_DIRECTORY | O_NOFOLLOW``), so no later swap of a
    component can redirect the walk. An absent component is created with ``os.mkdir(dir_fd=...)`` when ``create`` is
    set, else ``FileNotFoundError`` is raised; a component that is a symlink or not a directory raises ``_NotDirectory``
    (``ELOOP`` or ``ENOTDIR``); every other ``OSError`` is raised as it is. Every descriptor but the one returned is
    closed."""
    d = os.open(root, os.O_RDONLY | os.O_DIRECTORY)
    for i, name in enumerate(parents):
        try:
            try:
                nd = os.open(name, _DIR_FLAGS, dir_fd=d)
            except FileNotFoundError:
                if not create:
                    raise
                os.mkdir(name, dir_fd=d)
                nd = os.open(name, _DIR_FLAGS, dir_fd=d)
        except OSError as e:
            os.close(d)
            if e.errno in (errno.ELOOP, errno.ENOTDIR):
                raise _NotDirectory("/".join(parents[:i + 1])) from None
            raise
        os.close(d)
        d = nd
    return d


def _inspect(root: str, path: str):
    """``("absent",)``, ``("conflict", reason)`` or ``("text", content)`` for the target; every component is looked at
    with ``lstat`` first (a symlink is never followed), then reached through descriptors (``_open_parents``, and the
    last component opened ``O_NOFOLLOW | O_NONBLOCK`` from the parent's descriptor): the descriptor walk decides, so a
    component swapped after the ``lstat`` is never followed. Only a regular file is read."""
    parts = path.split("/")
    cur = root
    for i, part in enumerate(parts):
        cur = os.path.join(cur, part)
        try:
            st = os.lstat(cur)
        except FileNotFoundError:
            return ("absent",)
        except OSError as e:
            raise ManagedError("%s: cannot read (%s)" % (path, e.strerror)) from None
        if i < len(parts) - 1:
            if not stat.S_ISDIR(st.st_mode):
                return ("conflict", "parent %s is not a directory" % "/".join(parts[:i + 1]))
            continue
        if stat.S_ISLNK(st.st_mode):
            return ("conflict", "is a symlink")
        if not stat.S_ISREG(st.st_mode):
            return ("conflict", _NOT_MANAGED)
    try:
        d = _open_parents(root, parts[:-1], False)
    except _NotDirectory as e:  # a parent swapped to a symlink or a file after the lstat
        return ("conflict", "parent %s is not a directory" % e.args[0])
    except FileNotFoundError:
        return ("absent",)
    except OSError as e:
        raise ManagedError("%s: cannot read (%s)" % (path, e.strerror)) from None
    try:
        fd = os.open(parts[-1], os.O_RDONLY | os.O_NONBLOCK | os.O_NOFOLLOW, dir_fd=d)
    except FileNotFoundError:
        return ("absent",)
    except OSError as e:
        if e.errno == errno.ELOOP:  # a symlink put in place after the lstat
            return ("conflict", "is a symlink")
        raise ManagedError("%s: cannot read (%s)" % (path, e.strerror)) from None
    finally:
        os.close(d)
    try:
        if not stat.S_ISREG(os.fstat(fd).st_mode):
            return ("conflict", _NOT_MANAGED)
        chunks = []
        while True:
            chunk = os.read(fd, 1 << 20)
            if not chunk:
                break
            chunks.append(chunk)
    except OSError as e:
        raise ManagedError("%s: cannot read (%s)" % (path, e.strerror)) from None
    finally:
        os.close(fd)
    try:
        return ("text", b"".join(chunks).decode("utf-8"))
    except UnicodeDecodeError:
        return ("conflict", _NOT_MANAGED)


def plan(root: str, writes: list, version: str) -> tuple:
    """``(actions, conflicts)``: an action is ``(path, new_text)``; a conflict is ``"<path>: <reason>"``. Nothing is
    written. With any conflict the actions are ``[]``; an action whose text equals the file's is dropped."""
    _check_root(root)
    if type(writes) is not list:
        raise ManagedError("writes: must be a list")
    _check_version(version)
    counts: dict = {}
    for w in writes:
        if type(w) is not Write:
            raise ManagedError("writes: every item must be a Write")
        _check_path(w.path)
        _str(w.text, "text")
        _str(w.kind, "kind")
        if w.kind not in _WRITE_KINDS:
            raise ManagedError("kind: must be file, claude-block or gitignore-block")
        _encodable(w.path, w.text)
        counts[w.path] = counts.get(w.path, 0) + 1
    actions: list = []
    conflicts: list = []
    seen: set = set()
    for w in writes:
        if w.path in seen:
            continue
        seen.add(w.path)
        if counts[w.path] > 1:
            conflicts.append("%s: two writes name the same path" % w.path)
            continue
        if w.kind != "file":
            if w.path != _KIND_FILE[w.kind]:
                raise ManagedError("path: a %s write must name %s" % (w.kind, _KIND_FILE[w.kind]))
            _check_body(w.text, _KIND_STYLE[w.kind])
        state = _inspect(root, w.path)
        if state[0] == "conflict":
            conflicts.append("%s: %s" % (w.path, state[1]))
            continue
        content = state[1] if state[0] == "text" else None
        if w.kind == "file":
            if content is not None and not is_generated(content):
                conflicts.append("%s: %s" % (w.path, _NOT_MANAGED))
                continue
            new = w.text
        else:
            try:
                new = _put(content or "", _KIND_STYLE[w.kind], w.kind, version, w.text)
            except ManagedError as e:
                conflicts.append("%s: managed block malformed: %s" % (w.path, e))
                continue
        if new != content:
            actions.append((w.path, new))
    if conflicts:
        return [], conflicts
    return actions, conflicts


def _outside(p):
    """``(before, after, final_newline)`` of a parsed block (``_parse``'s tuple): the text before the begin line, the
    text after the end line's newline, and whether the end line had a newline."""
    b, e, _k, _n, _v, lines = p
    return ("".join(line + "\n" for line in lines[:b]), "\n".join(lines[e + 1:]), e != len(lines) - 1)


def _well_formed(text: str) -> list:
    """The styles in which ``text`` holds a well-formed block, each with its parse: ``[]`` for none (a malformed
    block of a style is not a block of that style), more than one for a text that quotes a block in the other style."""
    found = []
    for style in (HTML, HASH):
        try:
            p = _parse(text, style)
        except ManagedError:
            continue
        if p is not None:
            found.append((style, p))
    return found


def _marker_free(text: str) -> bool:
    """True when ``text`` has no marker-like line of either style."""
    try:
        return _parse(text, HTML) is None and _parse(text, HASH) is None
    except ManagedError:
        return False


def _accept(current: str, new: str) -> bool:
    """May ``new`` replace ``current``? The header marks the file as generated; otherwise the text outside the block
    must be the same (a block appended to a file without one may add one newline). The comment style is the one in
    which ``new`` holds a well-formed block, and ``current`` is read in that style only (``plan`` reads the kind's own
    style only); ``new`` with blocks of both styles is refused, and ``new`` with none leaves the whole-text rule."""
    if is_generated(current):
        return True
    found = _well_formed(new)
    if len(found) > 1:
        return False
    if not found:
        return current == new and _marker_free(current)
    style, p = found[0]
    nxt = _outside(p)
    try:
        cp = _parse(current, style)
    except ManagedError:
        return False
    if cp is None:
        before, after, final_newline = nxt
        want = current if current == "" or current.endswith("\n") else current + "\n"
        return after == "" and final_newline and before == want
    return _outside(cp) == nxt


def _recheck(root: str, path: str, new: str) -> Optional[str]:
    state = _inspect(root, path)
    if state[0] == "conflict":
        return state[1]
    if state[0] == "text" and not _accept(state[1], new):
        return _NOT_MANAGED
    return None


def _fail(message: str, written: list) -> ManagedError:
    if written:
        message += "; written before it: " + ", ".join(written)
    return ManagedError(message)


def apply(root: str, actions: list) -> list:
    """Write every ``(path, new_text)`` action; the paths written. Every action is re-checked from the two texts
    (what ``plan`` would now report) before anything is written and again just before its own write."""
    _check_root(root)
    if type(actions) is not list:
        raise ManagedError("actions: must be a list of (path, text) tuples of strings")
    for a in actions:
        if type(a) is not tuple or len(a) != 2 or type(a[0]) is not str or type(a[1]) is not str:
            raise ManagedError("actions: must be a list of (path, text) tuples of strings")
        _check_path(a[0])
        _encodable(a[0], a[1])
    problems: list = []
    seen: set = set()
    for path, new in actions:
        if path in seen:
            problems.append("%s: two writes name the same path" % path)
            continue
        seen.add(path)
        reason = _recheck(root, path, new)
        if reason is not None:
            problems.append("%s: %s" % (path, reason))
    if problems:
        raise ManagedError("apply refused: " + "; ".join(problems))
    written: list = []
    for path, new in actions:
        reason = _recheck(root, path, new)
        if reason is not None:
            raise _fail("apply refused: %s: %s" % (path, reason), written)
        try:
            _write(root, path, new)
        except _NotDirectory as e:  # a parent swapped after the re-check
            raise _fail("apply refused: %s: parent %s is not a directory" % (path, e.args[0]), written) from None
        except OSError as e:
            raise _fail("%s: cannot write (%s)" % (path, e.strerror), written) from None
        written.append(path)
    return written


def _umask() -> int:
    old = os.umask(0)
    os.umask(old)
    return old


_TEMP_TRIES = 100


def _temp(d: int):
    """``(fd, name)`` of a new temporary file in the directory ``d``: ``O_CREAT | O_EXCL | O_NOFOLLOW``, ``0o600``, a
    name with the ``.sd-managed-`` prefix and a random part, retried on ``EEXIST`` up to ``_TEMP_TRIES`` times."""
    for _ in range(_TEMP_TRIES):
        name = ".sd-managed-" + os.urandom(8).hex()
        try:
            return os.open(name, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600, dir_fd=d), name
        except FileExistsError:
            continue
    raise FileExistsError(errno.EEXIST, os.strerror(errno.EEXIST))


def _write(root: str, path: str, text: str) -> None:
    """Write ``text`` to ``path``: every component below ``root`` is reached through descriptors (``_open_parents``,
    an absent one created), the temporary file is made in the parent's descriptor and moved over the target with
    ``os.replace`` by descriptor, so no swap of a component can redirect the write outside ``root``. A parent that is
    a symlink or not a directory raises ``_NotDirectory``."""
    parts = path.split("/")
    d = _open_parents(root, parts[:-1], True)
    try:
        try:
            mode = stat.S_IMODE(os.stat(parts[-1], dir_fd=d, follow_symlinks=False).st_mode)
        except FileNotFoundError:
            mode = 0o666 & ~_umask()
        fd, tmp = _temp(d)
        try:
            try:
                view = memoryview(text.encode("utf-8"))
                while len(view):
                    view = view[os.write(fd, view):]
                os.fsync(fd)
                os.fchmod(fd, mode)
            finally:
                os.close(fd)
            os.replace(tmp, parts[-1], src_dir_fd=d, dst_dir_fd=d)
        except BaseException:
            try:
                os.unlink(tmp, dir_fd=d)
            except OSError:
                pass
            raise
    finally:
        os.close(d)
